/* Туториал политической системы Rev 4 (rules.md §9bis, design.md §16.4/§22.10).
   Тексты — дословные пересказы правил из rules.md §9bis; клиент тонкий:
   никаких чисел и вероятностей — только то, что игрок обязан знать по своду
   обязательных правил (пункты 11–15). Модальное окно открывается с экрана
   «Двор» и из сайдбара; состояние «показан один раз» хранится в localStorage
   (UI-настройка, не игровые данные — принцип 1 не нарушается). */
(function () {
  'use strict';

  const CHAPTERS = [
    {
      icon: '🎲',
      title: 'Фортуна и скрытые броски',
      ref: 'rules.md §9bis.1',
      body: [
        'Половина дел мира зависит от Фортуны: урожаи, бедствия, эпидемии,',
        'рыночные шоки и заговоры определяются скрытыми бросками случайности.',
        'Вы видите события — но не числа бросков и не точные вероятности.',
        '',
        'Фортуна приручается: мудрое, сбалансированное правление (statecraft)',
        'снижает вероятность неблагоприятных событий, а законы-амортизаторы',
        '(страховые, запасные) смягчают уже выпавший удар.',
      ],
    },
    {
      icon: '🏛',
      title: 'Элиты, интриги и заговоры',
      ref: 'rules.md §9bis.2',
      body: [
        'В каждой цивилизации действуют фракции элит — знать, жречество,',
        'торговцы, военные, ремесленники, писцы — со своей силой, лояльностью',
        'и обидами. Налоги и конфискации растят обиду, стабильность и льготы —',
        'лояльность.',
        '',
        'Правитель ведёт либеральную или тираническую линию. Тирания быстро',
        'гасит мятежи страхом, но накопленная жестокость имеет предел:',
        'перебор превращает обиду в ненависть и открывает дорогу заговору.',
        'Либерализм медленнее, зато устойчивее.',
        '',
        'Если недовольство элит превысит порог и Фортуна улыбнётся',
        'заговорщикам, происходит переворот. Власть переходит к победившей',
        'фракции механистически — выбрать наследника нельзя, можно лишь',
        'играть с новым государем. Цивилизация, законы и инфраструктура',
        'сохраняются.',
      ],
    },
    {
      icon: '⚖',
      title: 'Законы, риск и равновесие',
      ref: 'rules.md §9bis.3',
      body: [
        'Долгое постоянство ключевых законов снижает риск предпринимателей:',
        'капитал дешевеет, экономика растёт и усложняется — но теряет',
        'устойчивость к потрясениям. Стабильность вознаграждается и',
        'одновременно готовит более дорогой кризис.',
        '',
        'Недеяние — тоже действие. Ход без законодательных правок копит',
        '«силу пути»: лояльность элит растёт, давление заговора падает,',
        'а редко изданные указы обретают больший вес.',
        '',
        'Мир стремится к равновесию: чрезмерная милитаризация, налоговая',
        'тяжесть или скорость роста постепенно возвращаются к центру —',
        '«перегнувший ветвь ломает её».',
        '',
        'Пустые ниши награждают первых: производство и поселение в незанятых',
        'секторах и регионах дают бонус, гаснущий по мере заполнения.',
        'Демонстративная мудрость наказуема: дорогие витринные законы и',
        'церемонии растят обиды сословий. Тихое правление дешевле громкого.',
      ],
    },
    {
      icon: '🤝',
      title: 'Соперники действуют сами',
      ref: 'rules.md §9bis.4',
      body: [
        'Другие цивилизации ведут своих правителей с той же логикой: они',
        'конкурируют за рынки сбыта, занимают пустые ниши раньше, чем вы,',
        'двигают границы влияния и могут нарушить договор — тираны чаще,',
        'либералы реже. Их ставки и броски скрыты; следы их агентности',
        'видны в долях рынков и хронике.',
      ],
    },
    {
      icon: '📜',
      title: 'Отчёты могут льстить',
      ref: 'rules.md §9bis.5',
      body: [
        'Чем тираничнее двор, тем красивее отчёты: литературная хроника',
        'преувеличивает успехи, занижает риски и замалчивает неприятные',
        'события (часть доходит позже — через недоимки и слухи).',
        '',
        'Структурированные канонические цифры API всегда честны; искажается',
        'только нарративный слой, помеченный как таковой.',
        '',
        'Осторожный игрок сверяет слова хрониста с числами.',
      ],
    },
  ];

  /* ---- модальный просмотрщик глав ---- */
  let overlayEl = null;
  let idx = 0;

  function chapterNode(i) {
    const c = CHAPTERS[i];
    return P.h('div', { class: 'tut-chapter' },
      P.h('h3', {}, `${c.icon} ${c.title}`),
      P.h('pre', { class: 'tut-body', text: c.body.join('\n') }),
      P.h('div', { class: 'muted small' }, `Источник: ${c.ref}`));
  }

  function renderModal() {
    const host = document.getElementById('tut-body');
    if (!host) return;
    P.clear(host);
    host.appendChild(chapterNode(idx));
    document.getElementById('tut-progress').textContent =
      `Глава ${idx + 1} из ${CHAPTERS.length}`;
    document.getElementById('tut-prev').disabled = idx === 0;
    const next = document.getElementById('tut-next');
    next.textContent = idx === CHAPTERS.length - 1 ? 'Начать игру →' : 'Далее ›';
  }

  function close() {
    if (overlayEl && overlayEl.parentNode) overlayEl.parentNode.removeChild(overlayEl);
    overlayEl = null;
  }

  window.openPoliticsTutorial = function (startIdx) {
    idx = typeof startIdx === 'number' ? startIdx : 0;
    close();
    const root = document.getElementById('app') || document.body;
    overlayEl = P.h('div', { class: 'tut-overlay', onclick: (e) => {
      if (e.target === overlayEl) close();
    } },
      P.h('div', { class: 'tut-modal card' },
        P.h('div', { class: 'tut-head' },
          P.h('b', {}, 'Как устроен двор: политическая система «Поэмы»'),
          P.h('button', { class: 'secondary', text: '✕', onclick: close })),
        P.h('div', { class: 'muted small' },
          'Краткое объяснение правил Rev 4 — фортуна, элиты, законы, соперники ' +
          'и льстивые хроники. Полные правила: rules.md §9bis.'),
        P.h('div', { id: 'tut-body' }),
        P.h('div', { class: 'row' },
          P.h('button', { id: 'tut-prev', class: 'secondary', text: '‹ Назад',
            onclick: () => { if (idx > 0) { idx--; renderModal(); } } }),
          P.h('span', { id: 'tut-progress', class: 'muted small' }),
          P.h('div', { class: 'spacer' }),
          P.h('button', { id: 'tut-next', text: 'Далее ›', onclick: () => {
            if (idx < CHAPTERS.length - 1) { idx++; renderModal(); }
            else { localStorage.setItem('poem.tutorial.shown', '1'); close(); }
          } }))));
    root.appendChild(overlayEl);
    renderModal();
  };

  window.closePoliticsTutorial = close;

  /* Автопоказ при первом входе в приложение с включённым политическим слоем. */
  window.maybeShowPoliticsTutorial = function () {
    if (localStorage.getItem('poem.tutorial.shown')) return false;
    window.openPoliticsTutorial(0);
    return true;
  };
})();
